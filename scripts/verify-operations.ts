/** Integration checks in a disposable PostgreSQL schema, never in business tables.
 * Run with supported Node: node --env-file=.env --import tsx scripts/verify-operations.ts
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import pg from 'pg';
import { PrismaPg } from '@prisma/adapter-pg';
import { PrismaClient } from '../layers/menu/generated/prisma/client';
import { registerPayment, getAccounts, getPayments, localToday } from '../layers/menu/server/utils/payments';
import { createProductionRun, getProductionRuns, getShoppingList, updateShoppingItem } from '../layers/menu/server/utils/production';
import { getDeliveryBoard, updateDeliveryOperation, getOperationsDashboard } from '../layers/menu/server/utils/operations';
import { transitionDelivery, transitionOrder } from '../layers/menu/server/utils/orders';

assert.ok(process.env.DATABASE_URL, 'DATABASE_URL required');
const schema = `ops_verify_${randomUUID().replaceAll('-', '')}`;
const adminPool = new pg.Pool({ connectionString: process.env.DATABASE_URL });
const url = new URL(process.env.DATABASE_URL!);
// Both raw SQL and Prisma model queries must target only this schema.
url.searchParams.set('options', `-c search_path=${schema},public`);
const pool = new pg.Pool({ connectionString: url.toString() });
const db = new PrismaClient({ adapter: new PrismaPg(pool, { schema }) });
const shared = globalThis as unknown as { prisma?: PrismaClient };
const previous = shared.prisma;
const checks: string[] = [];
const actor = { id: randomUUID(), label: 'Verificación aislada' };
try {
  await adminPool.query(`CREATE SCHEMA "${schema}"`);
  const ddl = execFileSync(process.execPath, ['node_modules/prisma/build/index.js', 'migrate', 'diff', '--from-empty', '--to-schema', 'prisma/schema.prisma', '--script'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
  await pool.query(ddl);
  const safeguards = readFileSync('prisma/migrations/20261117020000_operations/migration.sql', 'utf8').split('-- Server-only operational data:')[1]!;
  await pool.query('-- ' + safeguards);
  shared.prisma = db;
  const cycle = await db.weeklyCycle.create({ data: { weekStart: new Date('2097-11-18'), status: 'CLOSED', orderCutoffAt: new Date('2097-11-15') } });
  const customer = await db.customer.create({ data: { nombre: 'Fixture aislada', telefono: '0000000000', ubicacion1: 'Dirección de prueba' } });
  const ingredient = await db.ingredient.create({ data: { nombre: 'Arroz', nombreNormalizado: 'arroz', categoria: 'Granos' } });
  const dish = await db.foodCatalogItem.create({ data: { nombre: 'Platillo elegido', descripcion: '', preparacion: '', calorias: 100, imagen: '', tipo: 'comida', recipeYield: 4, recipeIngredients: { create: { ingredientId: ingredient.id, cantidad: 1, unidad: 'kg', orden: 0 } } } });
  const order = await db.order.create({ data: { customerId: customer.id, cycleId: cycle.id, status: 'CONFIRMED', priceSnapshot: 100, planTitleSnapshot: 'Prueba', planVariantTitleSnapshot: 'Una comida', contactSnapshot: { nombre: 'Nombre guardado', telefono: '0000000000' }, deliveries: { create: { sequence: 1, scheduledDate: new Date(localToday()), locationNumber: 1, addressSnapshot: 'Dirección guardada' } } }, include: { deliveries: true } });
  const delivery = order.deliveries[0]!;
  await db.orderMenuSlot.create({ data: { orderId: order.id, deliveryId: delivery.id, dayOfWeek: 'LUNES', dayOrder: 1, slotType: 'COMIDA', contenedor: 'C25', notes: 'Sin picante', components: { create: { catalogItemId: dish.id, nombre: dish.nombre, descripcion: '', calorias: 100, imagen: '', tipo: 'comida', componentRole: 'PLATILLO_PRINCIPAL', isSubstitution: true } } } });
  const payload = { kind: 'PAYMENT', amount: 70, method: 'CASH', receivedAt: localToday(), reason: 'Prueba', idempotencyKey: randomUUID() };
  const concurrent = await Promise.allSettled([registerPayment(order.id, payload, actor), registerPayment(order.id, { ...payload, idempotencyKey: randomUUID() }, actor)]);
  assert.equal(concurrent.filter(c => c.status === 'fulfilled').length, 1);
  assert.equal((await getPayments(order.id)).account.paid, 70);
  const accepted = await db.orderPayment.findFirstOrThrow({ where: { orderId: order.id } });
  const retry = { ...payload, idempotencyKey: accepted.idempotencyKey };
  await Promise.all([registerPayment(order.id, retry, actor), registerPayment(order.id, retry, actor)]);
  assert.equal(await db.orderPayment.count(), 1);
  await assert.rejects(registerPayment(order.id, { ...retry, amount: 60 }, actor), { statusCode: 409 });
  await assert.rejects(registerPayment(order.id, { ...retry, kind: 'REFUND', amount: 71, idempotencyKey: randomUUID() }, actor), { statusCode: 409 });
  checks.push('Concurrent payments cannot overcollect; duplicate retries create one entry; changed retries and excess refunds rejected');
  await assert.rejects(db.orderPayment.update({ where: { id: accepted.id }, data: { amount: 1 } }));
  await assert.rejects(db.orderPayment.delete({ where: { id: accepted.id } }));
  const accounts = await getAccounts({ cycleId: cycle.id, view: 'balance' });
  assert.equal(accounts.items[0]?.customerName, 'Nombre guardado'); assert.equal(accounts.summary.balance, 30);
  assert.equal((await getAccounts({ search: `#${order.folio}` })).total, 1);
  checks.push('Immutable ledger and filtered account totals use stored contact and price');
  const key = randomUUID();
  const [runId, retriedRunId] = await Promise.all([createProductionRun(cycle.id, { requestKey: key }, actor), createProductionRun(cycle.id, { requestKey: key }, actor)]);
  assert.equal(runId, retriedRunId); assert.equal(await db.productionRun.count(), 1);
  const run = (await getProductionRuns(cycle.id))[0]!;
  assert.equal(run.stale, false); assert.equal(run.snapshot.shopping[0]?.quantity, 250);
  assert.equal(run.snapshot.meals[0]?.notes, 'Sin picante'); assert.equal(run.snapshot.meals[0]?.components[0]?.substitution, true);
  await assert.rejects(db.productionRun.update({ where: { id: runId }, data: { actorLabel: 'Changed' } }));
  let shopping = await getShoppingList(runId);
  const item = shopping.items[0]!;
  const expense = await db.expense.create({ data: { description: 'Compra aislada', amount: 20, category: 'ingredientes', paymentMethod: 'efectivo', expenseDate: new Date(localToday()), expenseType: 'variable' } });
  shopping = await updateShoppingItem(runId, item.id, { version: shopping.version, purchased: true, expenseId: expense.id }, actor);
  assert.equal(shopping.items[0]?.expenseId, expense.id);
  await assert.rejects(updateShoppingItem(runId, item.id, { version: shopping.version - 1, purchased: false, expenseId: null }, actor), { statusCode: 409 });
  assert.equal(await db.expense.count(), 1);
  await db.foodCatalogItem.update({ where: { id: dish.id }, data: { recipeYield: 2 } });
  const frozen = (await getProductionRuns(cycle.id))[0]!;
  assert.equal(frozen.stale, true); assert.equal(frozen.snapshot.shopping[0]?.quantity, 250);
  const newRunId = await createProductionRun(cycle.id, { requestKey: randomUUID() }, actor);
  assert.equal((await getShoppingList(newRunId)).items[0]?.quantity, 500);
  assert.equal((await getShoppingList(runId)).items[0]?.purchased, true);
  checks.push('Concurrent consolidation retries, immutable historical recipes, stale warnings and versioned purchases with expense links');
  const board = await getDeliveryBoard({ date: localToday() });
  assert.equal(board[0]?.balance, 30); assert.equal(board[0]?.address, 'Dirección guardada');
  await updateDeliveryOperation(delivery.id, { version: 1, assignedTo: 'Repartidor', incident: 'Llamar', evidenceUrl: 'https://example.com/evidence' }, actor);
  await assert.rejects(updateDeliveryOperation(delivery.id, { version: 1, assignedTo: '', incident: '', evidenceUrl: '' }, actor), { statusCode: 409 });
  assert.equal(await db.deliveryActivity.count(), 1);
  await transitionOrder(order.id, { version: 2, status: 'PREPARING' }, actor);
  await transitionDelivery(order.id, 1, { version: 3, status: 'OUT_FOR_DELIVERY' }, actor);
  assert.equal((await getProductionRuns(cycle.id))[0]?.stale, false);
  await transitionDelivery(order.id, 1, { version: 4, status: 'FAILED', reason: 'No recibió' }, actor);
  const dashboard = await getOperationsDashboard();
  assert.equal(dashboard.failed, 1); assert.equal(dashboard.balance, 30);
  await transitionOrder(order.id, { version: 5, status: 'CANCELLED', reason: 'Prueba de cancelación' }, actor);
  assert.equal((await getPayments(order.id)).account.refundable, 70);
  assert.equal((await getAccounts({ view: 'refund' })).summary.refundable, 70);
  assert.equal((await getDeliveryBoard({ date: localToday() })).length, 0);
  assert.equal((await getProductionRuns(cycle.id))[0]?.stale, true);
  await registerPayment(order.id, { ...retry, kind: 'REFUND', amount: 70, idempotencyKey: randomUUID() }, actor);
  assert.equal((await getPayments(order.id)).account.refundable, 0);
  checks.push('Delivery assignments are audited, stale writes rejected, status progression preserves consolidation and cancellation releases refund');
  const privacy = await pool.query(`SELECT tablename, rowsecurity FROM pg_tables WHERE schemaname=$1 AND tablename IN ('order_payments','production_runs','shopping_lists','shopping_items','delivery_activities')`, [schema]);
  assert.equal(privacy.rows.length, 5); assert.ok(privacy.rows.every(r => r.rowsecurity));
  const grant = await pool.query(`SELECT count(*)::int AS n FROM information_schema.role_table_grants WHERE table_schema=$1 AND grantee IN ('anon','authenticated','PUBLIC')`, [schema]);
  assert.equal(grant.rows[0].n, 0);
  checks.push('All operational tables enable RLS and deny direct anonymous/authenticated access');
} finally {
  shared.prisma = previous;
  await db.$disconnect(); await pool.end();
  await adminPool.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`);
  await adminPool.end();
}
checks.forEach(check => console.log(`PASS ${check}`));
console.log('Disposable schema removed; business records untouched.');
